export function getTraitBadgeLabel(sheep: SheepCreature, lang: Language): string {
  const t = translations[lang].personality.traits;
  const isGentle = sheep.hasRedBowTie || sheep.personality === '文静' || sheep.personality === '温顺' || sheep.personality === '善良';
  const isLively = sheep.hasHorns || sheep.personality === '活泼' || sheep.personality === '开朗' || sheep.personality === '暴躁';
  const isMelancholy = sheep.personality === '忧郁' || sheep.hasClosedEyes;

  if (isGentle) return `🎀 ${t.bowTie}`;
  if (isLively) return `📐 ${t.horns}`;
  if (isMelancholy) return `🌙 ${t.closedEyes}`;
  return `🐾 ${t.freeRoam}`;
}
